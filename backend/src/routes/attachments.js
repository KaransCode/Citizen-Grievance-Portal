import { Router } from 'express';
import path from 'node:path';
import { query } from '../utils/db.js';
import { requireAuth } from '../middleware/auth.js';
import { cloudinaryConfigured, getTimeLimitedCloudinaryUrl, uploadsDir } from '../services/storage.js';

const router = Router();

function mayReadAttachment(row, user) {
  if (user.role === 'ADMIN') return true;
  if (user.role === 'CITIZEN') return row.citizen_id === user.id;
  return user.role === 'DEPARTMENT'
    && Boolean(user.department_id)
    && row.assigned_department_id === user.department_id;
}

// Complaint evidence is served only after checking the logged-in user's access.
router.get('/:id/file', requireAuth, async (req, res, next) => {
  try {
    const result = await query(
      `SELECT a.id, a.storage_key, a.mime_type, c.citizen_id, c.assigned_department_id
       FROM complaint_attachments a
       JOIN complaints c ON c.id = a.complaint_id
       WHERE a.id = $1`,
      [req.params.id]
    );
    const attachment = result.rows[0];
    if (!attachment) return res.status(404).json({ message: 'Attachment not found.' });
    if (!mayReadAttachment(attachment, req.user)) {
      return res.status(404).json({ message: 'Attachment not found.' });
    }

    res.set({
      'Cache-Control': 'private, no-store',
      'X-Content-Type-Options': 'nosniff',
      'Content-Security-Policy': "default-src 'none'; sandbox"
    });

    if (cloudinaryConfigured) {
      return res.redirect(302, getTimeLimitedCloudinaryUrl(attachment.storage_key));
    }

    // Local storage keys are generated by the server; reject paths rather than
    // allowing any database value to be interpreted as a filesystem traversal.
    if (path.basename(attachment.storage_key) !== attachment.storage_key) {
      return res.status(404).json({ message: 'Attachment not found.' });
    }
    return res.type(attachment.mime_type).sendFile(
      path.join(uploadsDir, attachment.storage_key),
      (error) => { if (error) next(error); }
    );
  } catch (error) {
    next(error);
  }
});

export default router;
